/*
 * G474 MainブートローダーのFlash配置と起動条件を一元管理する。
 * 通常アプリ、metadata生成スクリプト、リンカ設定と同じ値を使用する。
 */
#pragma once

#include <stdint.h>

#define BOOTLOADER_FLASH_BASE UINT32_C(0x08000000)
#define BOOTLOADER_FLASH_SIZE UINT32_C(0x00008000)

#define BOOT_SLOT_A_BASE UINT32_C(0x08008000)
#define BOOT_SLOT_A_SIZE UINT32_C(0x00038000)
#define BOOT_SLOT_B_BASE UINT32_C(0x08040000)
#define BOOT_SLOT_B_SIZE UINT32_C(0x00038000)

#define BOOT_METADATA_BASE UINT32_C(0x08078000)
#define BOOT_METADATA_SIZE UINT32_C(0x00008000)

#define BOOT_SRAM1_BASE UINT32_C(0x20000000)
#define BOOT_SRAM1_END UINT32_C(0x20020000)
#define BOOT_CCMRAM_BASE UINT32_C(0x10000000)
#define BOOT_CCMRAM_END UINT32_C(0x10008000)

#define BOOT_IMAGE_METADATA_MAGIC UINT32_C(0x3157464F) /* ASCII "OFW1" (little endian) */
#define BOOT_IMAGE_METADATA_FORMAT UINT16_C(1)

typedef enum {
  BOOT_IMAGE_STATE_EMPTY = 0,
  BOOT_IMAGE_STATE_RECEIVING = 1,
  BOOT_IMAGE_STATE_VERIFIED = 2,
  BOOT_IMAGE_STATE_PENDING = 3,
  BOOT_IMAGE_STATE_CONFIRMED = 4,
  BOOT_IMAGE_STATE_INVALID = 5,
} boot_image_state_t;

typedef enum {
  BOOT_SLOT_A = 0,
  BOOT_SLOT_B = 1,
} boot_slot_t;
